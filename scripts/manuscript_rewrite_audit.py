#!/usr/bin/env python3
"""Audit of the journal rewrite of paper 1: label census, number check, move list and length figures.

Runs the three checks on the archived previous version and on the built journal version, then writes
the reports of manuscript/journal_rewrite/:

  label_census_before.csv, label_census_after.csv   one row per section and label category
  LABEL_CENSUS.md                                   before/after tables (prose; generated blocks apart)
  number_check_report.md                            every number of the typed text against the old text
  move_list.csv, MOVE_LIST.md                       where every block of the old version went
  COMPLIANCE.md                                     lengths and counts against the target conventions

Run after scripts/build_manuscript.py. Exit status 1 if the census finds a violation or the number
check finds a new number that is not allowed.

    python3 scripts/manuscript_rewrite_audit.py
"""
from __future__ import annotations

import csv
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "manuscript/journal_rewrite"
OLD_COMMIT = "4c4db9f024c518a0b7ed7bc8e9a901c61b3adedb"
OLD_MD = ROOT / "manuscript/archive/review_manuscript_draft_v0.5.1.md"
NEW_MD = ROOT / "manuscript/build/manuscript.md"
NEW_SUPP = ROOT / "manuscript/build/supplementary_information.md"
GEN = " [generated or verbatim]"

# Notes for old blocks with content that was condensed, moved or left out (block numbers of the archived v0.5.1).
NOTES = {
    1: "Draft note with the version history of the draft; the history is in the change log and the Git log.",
    5: "Sentence of the long structured abstract of the Markdown draft; the journal abstract (short, as in the "
       "v0.5.1 PDF) does not repeat it, and the Introduction states the same point.",
    6: "Objective paragraph of the long structured abstract; the aims are stated in the Introduction.",
    7: "Methods paragraph of the long structured abstract; the abstract now gives the methods in one sentence.",
    23: "Results paragraph of the long structured abstract; the exceptions are reported in Results.",
    86: "File names of the adjudication outputs and of the synthesis script; they are listed in the "
        "supplementary file index (manuscript/supplementary/README.md).",
}
PROCEDURAL = ("Methods", "Limitations", "Figures and tables", "Translate or encode")


def run(cmd: list[str]) -> str:
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode not in (0, 1):
        raise SystemExit(f"{' '.join(cmd)} failed:\n{r.stdout}\n{r.stderr}")
    return r.stdout + r.stderr


def census_tables() -> tuple[str, int]:
    old_tex = OUT / "old_main_tex_4c4db9f0.tex"
    old_tex.write_text(subprocess.run(["git", "show", f"{OLD_COMMIT}:manuscript/latex/main.tex"], cwd=ROOT,
                                      capture_output=True, text=True, check=True).stdout, encoding="utf-8")
    py = sys.executable
    run([py, "scripts/manuscript_label_census.py", "--md", str(OLD_MD), "--tex-frontmatter", str(old_tex),
         "--out", str(OUT / "label_census_before.csv"), "--allowed"])
    run([py, "scripts/manuscript_label_census.py", "--md", str(NEW_MD), "--md", str(NEW_SUPP),
         "--out", str(OUT / "label_census_after.csv"), "--allowed"])
    old_tex.unlink()
    before = list(csv.DictReader(open(OUT / "label_census_before.csv", encoding="utf-8")))
    after = list(csv.DictReader(open(OUT / "label_census_after.csv", encoding="utf-8")))

    def tally(rows, part):
        c, v = Counter(), Counter()
        for r in rows:
            gen = r["section"].endswith(GEN)
            if (part == "prose") != (not gen):
                continue
            c[r["category"]] += int(r["count"])
            if r["status"] == "violation":
                v[r["category"]] += int(r["count"])
        return c, v

    b, bv = tally(before, "prose")
    a, av = tally(after, "prose")
    g, _ = tally(after, "generated")
    cats = sorted(set(b) | set(a) | set(g), key=lambda k: -(b[k] + a[k]))
    lines = ["# Label census: previous version against the journal version", "",
             "Generated by `scripts/manuscript_rewrite_audit.py` with `scripts/manuscript_label_census.py`. "
             "Previous version: the archived Markdown master v0.5.1 (commit 4c4db9f0) with the abstract and "
             "Key Points of its `main.tex`. Journal version: `manuscript/build/manuscript.md` and "
             "`manuscript/build/supplementary_information.md`. A label is a token a reader cannot interpret "
             "without the project's files (see the script's docstring for the categories). A violation is a "
             "label outside the agreed exceptions: tool and model names (with versions) in Methods and the "
             "Supplementary Information, protocol and library versions in Methods, the Supplementary "
             "Information and Data availability, and paths and commit hashes in Data and code availability. "
             "Generated tables, the data-file list and the verbatim search strings are counted apart: they are "
             "not prose, and their identifiers sit in dedicated columns.", "",
             "## By category", "",
             "| Category | Before: prose | Before: violations | After: prose | After: violations | After: generated or verbatim |",
             "|---|---:|---:|---:|---:|---:|"]
    for k in cats:
        lines.append(f"| {k} | {b[k]} | {bv[k]} | {a[k]} | {av[k]} | {g[k]} |")
    lines.append(f"| **Total** | **{sum(b.values())}** | **{sum(bv.values())}** | **{sum(a.values())}** | "
                 f"**{sum(av.values())}** | **{sum(g.values())}** |")

    def by_section(rows):
        c, v = Counter(), Counter()
        for r in rows:
            if r["section"].endswith(GEN):
                continue
            c[r["section"]] += int(r["count"])
            if r["status"] == "violation":
                v[r["section"]] += int(r["count"])
        return c, v

    sb, sbv = by_section(before)
    sa, sav = by_section(after)
    lines += ["", "## By section (prose)", "", "| Version | Section | Labels | Violations |", "|---|---|---:|---:|"]
    lines += [f"| before | {s} | {n} | {sbv[s]} |" for s, n in sb.items()]
    lines += [f"| after | {s} | {n} | {sav[s]} |" for s, n in sa.items()]
    lines += ["", "## Labels left in the prose of the journal version", "",
              "| Section | Category | Count | Status | Occurrences |", "|---|---|---:|---|---|"]
    for r in after:
        if not r["section"].endswith(GEN):
            lines.append(f"| {r['section']} | {r['category']} | {r['count']} | {r['status']} | "
                         f"{r['examples'].replace('|', '/')} |")
    pl = re.search(r"placeholders: (\d+)", run([sys.executable, "scripts/manuscript_label_census.py", "--md", str(NEW_MD),
                                                  "--md", str(NEW_SUPP), "--out", "/dev/null", "--allowed"]))
    lines += ["", f"Draft placeholders ([CITE ...], [TODO ...]) in the journal version: {pl.group(1) if pl else 'n/a'}; "
                  "they are not counted as labels.", ""]
    (OUT / "LABEL_CENSUS.md").write_text("\n".join(lines), encoding="utf-8")
    return "\n".join(lines), sum(av.values())


def number_check() -> int:
    out = run([sys.executable, "scripts/manuscript_number_check.py", "--new", str(NEW_MD), "--new", str(NEW_SUPP),
               "--allow-new", str(OUT / "number_check_allowed_new.csv"), "--out", str(OUT / "number_check_report.md")])
    m = re.search(r"unallowed=(\d+)", out)
    return int(m.group(1)) if m else -1


def move_list() -> None:
    run([sys.executable, "scripts/manuscript_move_list.py", "--out-csv", str(OUT / "move_list.csv")])
    rows = list(csv.DictReader(open(OUT / "move_list.csv", encoding="utf-8")))
    for r in rows:
        if r["status"] in ("condensed", "not carried over") and int(r["old_block"]) not in NOTES:
            raise SystemExit(f"old block {r['old_block']} is {r['status']} but has no note")
    summary = defaultdict(Counter)
    for r in rows:
        summary[r["old_section"].split(" > ")[0]][r["status"]] += 1
    statuses = ["kept or moved", "reworded or split", "condensed", "not carried over"]
    lines = ["# Move list: where each block of the previous version went", "",
             "Generated by `scripts/manuscript_rewrite_audit.py` with `scripts/manuscript_move_list.py`. Every "
             "paragraph, list item and table of the archived v0.5.1 Markdown master "
             "(`manuscript/archive/review_manuscript_draft_v0.5.1.md`) is a numbered block; `move_list.csv` "
             "gives, for each block, its full old text, the new block that covers most of its content words, the "
             "new section that covers most, both coverages and the new text. Coverage measures shared content "
             "words, so it is a guide for reading, not a proof of equivalence; the numbers themselves are checked "
             "separately (`number_check_report.md`).", "",
             "## Summary by old section", "",
             "| Old section | " + " | ".join(statuses) + " |", "|---|" + "---:|" * len(statuses)]
    for sec, c in summary.items():
        lines.append(f"| {sec} | " + " | ".join(str(c[s]) for s in statuses) + " |")
    lines += ["", "## Blocks with a note on content that was condensed, moved or left out", "",
              "The status is the match status of the whole block; the note says which part of the block was "
              "condensed, moved or left out, and why.", "",
              "| Old block | Old section | Status | Note |", "|---:|---|---|---|"]
    for r in rows:
        if int(r["old_block"]) in NOTES:
            lines.append(f"| {r['old_block']} | {r['old_section']} | {r['status']} | {NOTES[int(r['old_block'])]} |")
    lines += ["", "## Procedural blocks of the previous version and their new place", "",
              "Old sections Methods, Limitations, the draft note and the Figures and tables list. Old blocks are "
              "numbered as in `move_list.csv`, where their full text is given.", "",
              "| Old block | Old section | New place | Status | Coverage (block / section) |", "|---:|---|---|---|---|"]
    for r in rows:
        if r["old_section"].startswith(PROCEDURAL) or "Limitations" in r["old_section"]:
            lines.append(f"| {r['old_block']} | {r['old_section']} | {r['new_file']}: {r['new_section']} | "
                         f"{r['status']} | {r['best_block_coverage']} / {r['best_section_coverage']} |")
    (OUT / "MOVE_LIST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def words(text: str) -> int:
    text = re.sub(r"<!--.*?-->|\[\[S:[a-z_]+\]\]", " ", text)
    return len(re.findall(r"[A-Za-z0-9][\w'’.\-–/×%]*", text))


def compliance() -> None:
    md = NEW_MD.read_text(encoding="utf-8")
    parts = re.split(r"^## (.+)$", md, flags=re.M)
    sec = {parts[i].strip(): parts[i + 1] for i in range(1, len(parts) - 1, 2)}
    body_names = ["Introduction", "Methods", "Results", "Discussion", "Conclusions"]

    def prose(text: str) -> str:
        return "\n".join(l for l in text.split("\n") if not l.startswith("|"))

    def table_words(text: str) -> int:
        return words("\n".join(l for l in text.split("\n") if l.startswith("|") and not re.match(r"^\|[-:| ]+\|$", l)))

    body = {n: words(prose(sec[n])) for n in body_names}
    tables = sum(table_words(sec[n]) for n in body_names)
    legends = words(sec["Figure legends"])
    kp = len(re.findall(r"^- ", sec["Key Points"], flags=re.M))
    kw = len([k for k in sec["Keywords"].strip().split(";") if k.strip()])
    abstract = words(sec["Abstract"])
    bbl = (ROOT / "manuscript/latex/main.bbl").read_text(encoding="utf-8")
    refs = len(re.findall(r"\\bibitem\{", bbl))
    log = (ROOT / "manuscript/latex/main.log").read_text(encoding="utf-8", errors="replace")
    pages = re.search(r"Output written on main\.pdf \((\d+) pages", log)
    numbering = list(csv.DictReader(open(ROOT / "manuscript/build/supplementary_numbering.csv", encoding="utf-8")))
    sup = Counter(r["type"] for r in numbering)
    figs = len(re.findall(r"^- \*\*Figure \d", sec["Figure legends"], flags=re.M))
    main_tables = len(re.findall(r"^\|---", md, flags=re.M)) - 1  # the reporting card is part of Box 1
    rows = [("Abstract (words)", abstract, "short, unstructured; recent scoping and systematic reviews in the target journal: 168–258"),
            ("Keywords", kw, "up to 6"),
            ("Key Points", kp, "up to 5 brief bullet points, shown at the end of the article"),
            ("Main text, Introduction to Conclusions, prose (words)", sum(body.values()),
             "Review articles: guide value 2,000–7,000 words; the recent reviews read have about 8,400–10,800 words of body text"),
            ("of which Introduction / Methods / Results / Discussion / Conclusions",
             " / ".join(str(body[n]) for n in body_names), ""),
            ("Words in main-text tables and Box 1 card", tables, ""),
            ("Figure legends (words)", legends, ""),
            ("Figures / tables in the article", f"{figs} / {main_tables}", "Box 1 holds the comparison protocol and the reporting card"),
            ("References", refs, "numbered, in order of citation; all included records cited"),
            ("Pages of the typeset article", pages.group(1) if pages else "n/a", "OUP authoring template, contemporary layout"),
            ("Supplementary Notes / Tables / Figures", f"{sup['Note']} / {sup['Table']} / {sup['Figure']}",
             "numbered by type in the order of first citation")]
    lines = ["# Lengths and counts of the journal version", "",
             "Generated by `scripts/manuscript_rewrite_audit.py` from `manuscript/build/manuscript.md`, the "
             "LaTeX build and the supplementary numbering. Words are counted as tokens of letters or digits.", "",
             "| Item | Value | Target convention |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    (OUT / "COMPLIANCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    _, violations = census_tables()
    unallowed = number_check()
    move_list()
    compliance()
    print({"census_violations": violations, "unallowed_new_numbers": unallowed})
    return 1 if violations or unallowed else 0


if __name__ == "__main__":
    raise SystemExit(main())
